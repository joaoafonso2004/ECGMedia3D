/**
 * Testes das notificações e do fluxo de aprovação (base de dados).
 *
 * Corre as migrações de supabase/migrations num PostgreSQL em memória
 * (PGlite), com um ambiente semelhante ao do Supabase: roles anon e
 * authenticated, auth.uid() e políticas RLS ativas.
 *
 *   npm test
 */
import { describe, it, before } from 'node:test';
import assert from 'node:assert/strict';
import { readFileSync, readdirSync } from 'node:fs';
import { join } from 'node:path';
import { PGlite } from '@electric-sql/pglite';

const MIGRACOES = join(import.meta.dirname, '..', 'supabase', 'migrations');

const ALUNO   = '00000000-0000-0000-0000-00000000000a';
const ALUNO2  = '00000000-0000-0000-0000-00000000000b';
const GESTOR1 = '00000000-0000-0000-0000-0000000000a1';
const GESTOR2 = '00000000-0000-0000-0000-0000000000a2';
const GESTOR_OUTRA = '00000000-0000-0000-0000-0000000000a3';
const ADMIN   = '00000000-0000-0000-0000-00000000000f';

const MOD_COM_GESTOR = 1;
const MOD_SEM_GESTOR = 2;

let db;

/** Executa SQL como um utilizador autenticado no site (como o PostgREST faz). */
async function como(uid, sql, params) {
  await db.exec(`set role authenticated; select set_config('request.jwt.claim.sub', '${uid}', false);`);
  try {
    return await db.query(sql, params);
  } finally {
    await db.exec(`reset role; select set_config('request.jwt.claim.sub', '', false);`);
  }
}

const notificacoesDe = async (uid) => (await db.query(
  `select tipo, titulo, mensagem, link, lida, id_media_items
     from notificacoes where id_destinatario = $1 order by id_notificacao`, [uid])).rows;

async function novoTrabalho(autor, titulo = 'Trabalho de teste') {
  const { rows } = await como(autor,
    `insert into media_items (titulo, status, id_autor) values ($1, 'pessoal', $2) returning id_media_items`,
    [titulo, autor]);
  return rows[0].id_media_items;
}

const submeter = (autor, id, modulo) =>
  como(autor, `update media_items set status = 'pendente', id_modulo = ${modulo} where id_media_items = ${id}`);

const decidir = (quem, id, estado) =>
  como(quem, `update media_items set status = '${estado}' where id_media_items = ${id}`);

before(async () => {
  db = new PGlite();

  // Ambiente do Supabase + as tabelas existentes que as notificações usam
  await db.exec(`
    create role anon nologin;
    create role authenticated nologin;
    create schema auth;
    create function auth.uid() returns uuid language sql stable as
      $$ select nullif(current_setting('request.jwt.claim.sub', true), '')::uuid $$;
    grant usage on schema auth, public to anon, authenticated;
    alter default privileges in schema public grant all on tables to anon, authenticated;
    alter default privileges in schema public grant all on sequences to anon, authenticated;
    create publication supabase_realtime;

    create table utilizadores (id_utilizadores uuid primary key, nome text, email text);
    create table modulo (id_modulo bigint primary key, nome text);
    create table media_items (
      id_media_items bigint generated by default as identity primary key,
      titulo text, status text, id_autor uuid references utilizadores, id_modulo bigint references modulo
    );
    create table tipo_utilizador (
      id_tipo_utilizador bigint generated by default as identity primary key,
      id_utilizador uuid references utilizadores, role text, id_modulo bigint references modulo
    );

    insert into utilizadores values
      ('${ALUNO}', 'Ana Aluna', 'ana@teste.pt'), ('${ALUNO2}', 'Rui Aluno', 'rui@teste.pt'),
      ('${GESTOR1}', 'Gil Gestor', 'gil@teste.pt'), ('${GESTOR2}', 'Gabi Gestora', 'gabi@teste.pt'),
      ('${GESTOR_OUTRA}', 'Óscar Gestor', 'oscar@teste.pt'), ('${ADMIN}', 'Sara Admin', 'sara@teste.pt');
    insert into modulo values (${MOD_COM_GESTOR}, 'Modelação 3D'), (${MOD_SEM_GESTOR}, 'Animação'), (3, 'Multimédia');
    insert into tipo_utilizador (id_utilizador, role, id_modulo) values
      ('${ALUNO}', 'utilizador', ${MOD_COM_GESTOR}), ('${ALUNO2}', 'utilizador', ${MOD_COM_GESTOR}),
      ('${GESTOR1}', 'gestor', null), ('${GESTOR1}', 'gestor_disciplina', ${MOD_COM_GESTOR}),
      ('${GESTOR2}', 'gestor_disciplina', ${MOD_COM_GESTOR}),
      ('${GESTOR_OUTRA}', 'gestor_disciplina', 3),
      ('${ADMIN}', 'superadmin', null);

    -- Permissões base de media_items (cada um mexe no seu; gestores em tudo)
    alter table media_items enable row level security;
    create policy media_leitura on media_items for select using (true);
    create policy media_insert on media_items for insert to authenticated with check (id_autor = auth.uid());
    create policy media_update on media_items for update to authenticated using (true);
  `);

  // Todas as migrações, por ordem
  for (const f of readdirSync(MIGRACOES).filter(f => f.endsWith('.sql')).sort()) {
    await db.exec(readFileSync(join(MIGRACOES, f), 'utf8'));
  }
});

describe('Migrações', () => {
  it('podem ser corridas mais do que uma vez', async () => {
    for (const f of readdirSync(MIGRACOES).filter(f => f.endsWith('.sql')).sort()) {
      await db.exec(readFileSync(join(MIGRACOES, f), 'utf8'));
    }
  });

  it('ativam o tempo real na tabela de notificações', async () => {
    const { rows } = await db.query(
      `select 1 from pg_publication_tables where pubname = 'supabase_realtime' and tablename = 'notificacoes'`);
    assert.equal(rows.length, 1);
  });
});

describe('Pedido de aprovação', () => {
  it('criar um trabalho pessoal não notifica ninguém', async () => {
    await novoTrabalho(ALUNO2, 'Rascunho');
    const { rows } = await db.query(`select count(*)::int as n from notificacoes`);
    assert.equal(rows[0].n, 0);
  });

  it('notifica todos os gestores da disciplina, com link para as Aprovações', async () => {
    const id = await novoTrabalho(ALUNO, 'Robô animado');
    await submeter(ALUNO, id, MOD_COM_GESTOR);

    for (const gestor of [GESTOR1, GESTOR2]) {
      const [n] = (await notificacoesDe(gestor)).filter(n => n.id_media_items === id);
      assert.equal(n.tipo, 'submissao_pendente');
      assert.equal(n.link, '/gestor/aprovacoes');
      assert.equal(n.mensagem, 'Ana Aluna submeteu "Robô animado" em Modelação 3D.');
    }
  });

  it('não notifica gestores de outras disciplinas nem o superadmin', async () => {
    assert.equal((await notificacoesDe(GESTOR_OUTRA)).length, 0);
    assert.equal((await notificacoesDe(ADMIN)).length, 0);
  });

  it('repetir o mesmo estado não cria notificações duplicadas', async () => {
    const id = await novoTrabalho(ALUNO, 'Sem duplicados');
    await submeter(ALUNO, id, MOD_COM_GESTOR);
    await submeter(ALUNO, id, MOD_COM_GESTOR);
    const doPedido = (await notificacoesDe(GESTOR1)).filter(n => n.id_media_items === id);
    assert.equal(doPedido.length, 1);
  });

  it('numa disciplina sem gestor, avisa o superadmin', async () => {
    const id = await novoTrabalho(ALUNO, '');
    await submeter(ALUNO, id, MOD_SEM_GESTOR);
    const [n] = await notificacoesDe(ADMIN);
    assert.equal(n.titulo, 'Pedido de aprovação sem gestor');
    assert.match(n.mensagem, /"Sem título" em Animação, mas a disciplina não tem gestor/);
  });
});

describe('Decisão do gestor', () => {
  it('aprovar avisa o autor e arquiva o pedido para os outros gestores', async () => {
    const id = await novoTrabalho(ALUNO, 'Para aprovar');
    await submeter(ALUNO, id, MOD_COM_GESTOR);
    await decidir(GESTOR1, id, 'aprovado');

    const aviso = (await notificacoesDe(ALUNO)).find(n => n.id_media_items === id);
    assert.equal(aviso.tipo, 'conteudo_aprovado');
    assert.equal(aviso.link, '/utilizador/biblioteca');

    const pedidoGestor2 = (await notificacoesDe(GESTOR2)).find(n => n.id_media_items === id);
    assert.equal(pedidoGestor2.lida, true);
  });

  it('rejeitar avisa o autor', async () => {
    const id = await novoTrabalho(ALUNO, 'Para rejeitar');
    await submeter(ALUNO, id, MOD_COM_GESTOR);
    await decidir(GESTOR2, id, 'rejeitado');
    const aviso = (await notificacoesDe(ALUNO)).find(n => n.id_media_items === id);
    assert.equal(aviso.tipo, 'conteudo_rejeitado');
  });

  it('o superadmin decide pedidos de disciplinas sem gestor', async () => {
    const id = await novoTrabalho(ALUNO, 'Sem gestor');
    await submeter(ALUNO, id, MOD_SEM_GESTOR);
    await decidir(ADMIN, id, 'aprovado');
    const aviso = (await notificacoesDe(ALUNO)).find(n => n.id_media_items === id);
    assert.equal(aviso.tipo, 'conteudo_aprovado');
  });

  it('remover da galeria avisa o autor', async () => {
    const id = await novoTrabalho(ALUNO, 'Para remover');
    await submeter(ALUNO, id, MOD_COM_GESTOR);
    await decidir(GESTOR1, id, 'aprovado');
    await decidir(GESTOR1, id, 'pessoal');
    const avisos = (await notificacoesDe(ALUNO)).filter(n => n.id_media_items === id);
    assert.equal(avisos.at(-1).tipo, 'conteudo_removido');
  });

  it('o autor que retira o próprio trabalho da galeria não é avisado de si mesmo', async () => {
    const id = await novoTrabalho(ALUNO, 'Retirado pelo autor');
    await submeter(ALUNO, id, MOD_COM_GESTOR);
    await decidir(GESTOR1, id, 'aprovado');
    await decidir(ALUNO, id, 'pessoal');
    const avisos = (await notificacoesDe(ALUNO)).filter(n => n.id_media_items === id);
    assert.deepEqual(avisos.map(n => n.tipo), ['conteudo_aprovado']);
  });

  it('cancelar o pedido arquiva o aviso dos gestores', async () => {
    const id = await novoTrabalho(ALUNO, 'Cancelado');
    await submeter(ALUNO, id, MOD_COM_GESTOR);
    await decidir(ALUNO, id, 'pessoal');
    const pedido = (await notificacoesDe(GESTOR1)).find(n => n.id_media_items === id);
    assert.equal(pedido.lida, true);
  });

  it('apagar o trabalho apaga as notificações associadas', async () => {
    const id = await novoTrabalho(ALUNO, 'Para apagar');
    await submeter(ALUNO, id, MOD_COM_GESTOR);
    await db.query(`delete from media_items where id_media_items = $1`, [id]);
    const { rows } = await db.query(`select count(*)::int as n from notificacoes where id_media_items = $1`, [id]);
    assert.equal(rows[0].n, 0);
  });
});

describe('Segurança do fluxo de aprovação', () => {
  it('um aluno não consegue aprovar o próprio trabalho', async () => {
    const id = await novoTrabalho(ALUNO, 'Batota');
    await submeter(ALUNO, id, MOD_COM_GESTOR);
    await assert.rejects(decidir(ALUNO, id, 'aprovado'), /Só um gestor desta disciplina/);
  });

  it('um gestor de outra disciplina não consegue decidir', async () => {
    const id = await novoTrabalho(ALUNO, 'Disciplina errada');
    await submeter(ALUNO, id, MOD_COM_GESTOR);
    await assert.rejects(decidir(GESTOR_OUTRA, id, 'rejeitado'), /Só um gestor desta disciplina/);
  });

  it('um aluno não consegue criar um trabalho já aprovado', async () => {
    await assert.rejects(
      como(ALUNO, `insert into media_items (titulo, status, id_autor, id_modulo) values ('x', 'aprovado', '${ALUNO}', ${MOD_COM_GESTOR})`),
      /Só um gestor desta disciplina/);
  });
});

describe('Permissões das notificações (RLS)', () => {
  it('cada utilizador só vê as suas', async () => {
    const { rows } = await como(ALUNO, `select distinct id_destinatario from notificacoes`);
    assert.deepEqual(rows.map(r => r.id_destinatario), [ALUNO]);
  });

  it('o browser não consegue criar notificações', async () => {
    await assert.rejects(como(ALUNO,
      `insert into notificacoes (id_destinatario, tipo, titulo) values ('${GESTOR1}', 'submissao_pendente', 'Falsa')`),
      /permission denied/);
  });

  it('o browser só pode alterar o campo "lida"', async () => {
    await assert.rejects(como(ALUNO, `update notificacoes set titulo = 'Alterado'`), /permission denied/);
    const { rows } = await como(ALUNO, `update notificacoes set lida = true returning id_notificacao`);
    assert.ok(rows.length > 0);
  });

  it('ninguém mexe nas notificações dos outros', async () => {
    const { rows } = await como(ALUNO, `update notificacoes set lida = false where id_destinatario = '${GESTOR1}' returning 1`);
    assert.equal(rows.length, 0);
    const apagadas = await como(ALUNO, `delete from notificacoes where id_destinatario = '${GESTOR1}' returning 1`);
    assert.equal(apagadas.rows.length, 0);
  });

  it('as funções dos triggers não podem ser chamadas diretamente', async () => {
    await assert.rejects(como(ALUNO, `select public.notificar_estado_media()`));
  });
});

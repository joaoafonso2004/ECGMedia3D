/**
 * Testes das regras de cargos (tabela tipo_utilizador).
 *
 * Corre a migração 20261125_cargos_seguranca.sql num PostgreSQL em memória
 * (PGlite), com roles anon e authenticated, auth.uid() e RLS ativo.
 *
 *   npm test
 */
import { describe, it, before } from 'node:test';
import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { join } from 'node:path';
import { PGlite } from '@electric-sql/pglite';

const MIGRACAO = join(import.meta.dirname, '..', 'supabase', 'migrations', '20261125_cargos_seguranca.sql');

const NOVO    = '00000000-0000-0000-0000-000000000001';
const ALUNO   = '00000000-0000-0000-0000-00000000000a';
const GESTOR  = '00000000-0000-0000-0000-0000000000a1';
const OUTRO   = '00000000-0000-0000-0000-0000000000a2';
const ADMIN   = '00000000-0000-0000-0000-00000000000f';

const MOD_DO_GESTOR = 1;
const MOD_DE_OUTRO = 2;

let db;

/** Executa SQL como um utilizador autenticado no site (como o PostgREST faz). */
async function como(uid, sql, params) {
  await db.exec(`set role authenticated; select set_config('request.jwt.claim.sub', '${uid}', false);`);
  try {
    return await db.query(sql, params);
  } finally {
    await db.exec(`reset role; select set_config('request.jwt.claim.sub', '', false);`);
  }
}

const darCargo = (quem, alvo, role, modulo = null) =>
  como(quem, `insert into tipo_utilizador (id_utilizador, role, id_modulo) values ($1, $2, $3)`,
    [alvo, role, modulo]);

const cargosDe = async (uid) => (await db.query(
  `select role, id_modulo from tipo_utilizador where id_utilizador = $1 order by id_tipo_utilizador`, [uid])).rows;

const recusa = (promessa) => assert.rejects(promessa, /row-level security/);

before(async () => {
  db = new PGlite();
  await db.exec(`
    create role anon nologin;
    create role authenticated nologin;
    create schema auth;
    create function auth.uid() returns uuid language sql stable as
      $$ select nullif(current_setting('request.jwt.claim.sub', true), '')::uuid $$;
    grant usage on schema auth, public to anon, authenticated;
    alter default privileges in schema public grant all on tables to anon, authenticated;
    alter default privileges in schema public grant all on sequences to anon, authenticated;

    create table utilizadores (id_utilizadores uuid primary key, nome text);
    create table modulo (id_modulo bigint primary key, nome text);
    create table tipo_utilizador (
      id_tipo_utilizador bigint generated by default as identity primary key,
      id_utilizador uuid references utilizadores on delete cascade,
      role text, id_entidade bigint, id_programa bigint, id_modulo bigint references modulo
    );

    -- A regra antiga (de 01_esquema_base.sql): qualquer gestor dava qualquer cargo
    alter table tipo_utilizador enable row level security;
    create policy "tipo_utilizador_insert" on tipo_utilizador for insert to authenticated
      with check (exists (select 1 from tipo_utilizador t where t.id_utilizador = auth.uid()
                           and t.role in ('superadmin', 'gestor', 'gestor_disciplina'))
                  or (id_utilizador = auth.uid() and role = 'utilizador'));
    create policy "regra_antiga_com_outro_nome" on tipo_utilizador for all to authenticated
      using (true) with check (true);

    insert into utilizadores values
      ('${NOVO}', 'Conta nova'), ('${ALUNO}', 'Ana Aluna'), ('${GESTOR}', 'Gil Gestor'),
      ('${OUTRO}', 'Óscar Gestor'), ('${ADMIN}', 'Sara Admin');
    insert into modulo values (${MOD_DO_GESTOR}, 'Modelação 3D'), (${MOD_DE_OUTRO}, 'Animação');
    insert into tipo_utilizador (id_utilizador, role, id_modulo) values
      ('${ALUNO}', 'utilizador', null),
      ('${GESTOR}', 'gestor', null), ('${GESTOR}', 'gestor_disciplina', ${MOD_DO_GESTOR}),
      ('${OUTRO}', 'gestor_disciplina', ${MOD_DE_OUTRO}),
      ('${ADMIN}', 'superadmin', null);
  `);
  await db.exec(readFileSync(MIGRACAO, 'utf8'));
});

describe('Migração dos cargos', () => {
  it('pode ser corrida mais do que uma vez', async () => {
    await db.exec(readFileSync(MIGRACAO, 'utf8'));
  });

  it('tira as regras de escrita antigas, mesmo com outro nome', async () => {
    const { rows } = await db.query(
      `select policyname from pg_policies where tablename = 'tipo_utilizador' order by policyname`);
    assert.deepEqual(rows.map(r => r.policyname), [
      'tipo_utilizador_delete', 'tipo_utilizador_insert', 'tipo_utilizador_leitura', 'tipo_utilizador_update',
    ]);
  });
});

describe('Registo de uma conta nova', () => {
  it('pode dar a si própria o role utilizador, sem disciplina', async () => {
    await darCargo(NOVO, NOVO, 'utilizador');
    assert.deepEqual(await cargosDe(NOVO), [{ role: 'utilizador', id_modulo: null }]);
  });

  it('não pode dar a si própria o cargo de gestor nem de superadmin', async () => {
    await recusa(darCargo(NOVO, NOVO, 'gestor'));
    await recusa(darCargo(NOVO, NOVO, 'superadmin'));
  });

  it('não se pode juntar sozinha a uma disciplina', async () => {
    await recusa(darCargo(ALUNO, ALUNO, 'utilizador', MOD_DO_GESTOR));
  });
});

describe('Gestor de disciplina', () => {
  it('associa um aluno à disciplina que gere', async () => {
    await darCargo(GESTOR, ALUNO, 'utilizador', MOD_DO_GESTOR);
    assert.ok((await cargosDe(ALUNO)).some(c => c.id_modulo === MOD_DO_GESTOR));
  });

  it('não associa alunos a disciplinas de outro gestor', async () => {
    await recusa(darCargo(GESTOR, ALUNO, 'utilizador', MOD_DE_OUTRO));
  });

  it('não se faz superadmin a si próprio', async () => {
    await recusa(darCargo(GESTOR, GESTOR, 'superadmin'));
  });

  it('não dá cargos de gestor, nem a si próprio noutra disciplina', async () => {
    await recusa(darCargo(GESTOR, ALUNO, 'gestor_disciplina', MOD_DO_GESTOR));
    await recusa(darCargo(GESTOR, GESTOR, 'gestor_disciplina', MOD_DE_OUTRO));
  });

  it('não muda o seu cargo para superadmin', async () => {
    await como(GESTOR, `update tipo_utilizador set role = 'superadmin' where id_utilizador = $1`, [GESTOR]);
    assert.ok(!(await cargosDe(GESTOR)).some(c => c.role === 'superadmin'));
  });

  it('não apaga o cargo do administrador', async () => {
    await como(GESTOR, `delete from tipo_utilizador where id_utilizador = $1`, [ADMIN]);
    assert.deepEqual(await cargosDe(ADMIN), [{ role: 'superadmin', id_modulo: null }]);
  });

  it('tira um aluno da disciplina que gere, mas não de outras', async () => {
    await db.query(`insert into tipo_utilizador (id_utilizador, role, id_modulo) values ($1, 'utilizador', $2)`,
      [ALUNO, MOD_DE_OUTRO]);
    await como(GESTOR, `delete from tipo_utilizador where id_utilizador = $1 and id_modulo is not null`, [ALUNO]);
    assert.deepEqual((await cargosDe(ALUNO)).map(c => c.id_modulo), [null, MOD_DE_OUTRO]);
  });
});

describe('Superadmin', () => {
  it('dá e tira o cargo de gestor de disciplina', async () => {
    await darCargo(ADMIN, OUTRO, 'gestor_disciplina', MOD_DO_GESTOR);
    assert.ok((await cargosDe(OUTRO)).some(c => c.id_modulo === MOD_DO_GESTOR));
    await como(ADMIN, `delete from tipo_utilizador where id_utilizador = $1 and id_modulo = $2`,
      [OUTRO, MOD_DO_GESTOR]);
    assert.ok(!(await cargosDe(OUTRO)).some(c => c.id_modulo === MOD_DO_GESTOR));
  });

  it('associa alunos a qualquer disciplina', async () => {
    await darCargo(ADMIN, NOVO, 'utilizador', MOD_DE_OUTRO);
    assert.ok((await cargosDe(NOVO)).some(c => c.id_modulo === MOD_DE_OUTRO));
  });
});

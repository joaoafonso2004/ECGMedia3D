/** Executa SQL como um utilizador do site (como o PostgREST faz) e guarda o efeito. */
async function como(uid, texto, params) {
  await db.exec(`set role ${uid ? 'authenticated' : 'anon'}; select set_config('request.jwt.claim.sub', '${uid ?? ''}', false);`);
  try {
    return await db.query(texto, params);
  } finally {
    await db.exec(`reset role; select set_config('request.jwt.claim.sub', '', false);`);
  }
}

/** Tenta a operação e desfaz tudo no fim. true se passou e mexeu em pelo menos uma linha. */
async function tenta(uid, texto, params) {
  await db.exec('begin');
  try {
    await db.exec(`set local role ${uid ? 'authenticated' : 'anon'}; select set_config('request.jwt.claim.sub', '${uid ?? ''}', true);`);
    const r = await db.query(texto, params);
    return (r.affectedRows ?? 0) > 0 || r.rows.length > 0;
  } catch {
    return false;
  } finally {
    await db.exec('rollback');
  }
}


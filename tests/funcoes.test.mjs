  'criar um programa':                  [`insert into programa (nome, id_entidade) values ('Novo', ${x.e})`],
  'editar o programa':                  [`update programa set nome = nome || '.' where id_programa = ${x.p1}`],
  'apagar o programa':                  [`delete from programa where id_programa = ${x.p1}`],
  'criar um módulo no programa':        [`insert into modulo (nome, id_programa) values ('Novo', ${x.p1})`],
  'editar o módulo':                    [`update modulo set nome = nome || '.' where id_modulo = ${x.m1}`],
  'apagar o módulo':                    [`delete from modulo where id_modulo = ${x.m1}`],

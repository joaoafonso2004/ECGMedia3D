-- ════════════════════════════════════════════════════════════════════
-- Terminologia configurável
--
-- Os nomes dos níveis da hierarquia (entidade → programa → módulo →
-- projeto) deixam de estar fixos no código. Cada tipo de entidade tem
-- os seus termos (uma escola tem "Programas" e "Disciplinas"; uma
-- empresa pode ter "Departamentos" e "Serviços") e uma entidade pode
-- ainda substituir termos só para si.
--
-- Precedência: entidade específica → tipo de entidade → predefinição.
-- Cada termo guarda singular, plural e género, para as frases da
-- interface concordarem ("Novo programa", "Nova disciplina"), e o
-- idioma, que prepara o multi-idioma (PT/EN).
--
-- Leitura pública; só o superadmin altera.
-- ════════════════════════════════════════════════════════════════════

create table if not exists public.terminologia (
  id_terminologia bigint generated by default as identity primary key,
  tipo_entidade   text check (tipo_entidade = lower(btrim(tipo_entidade)) and tipo_entidade <> ''),
  id_entidade     bigint references public.entidade (id_entidade) on delete cascade,
  idioma          text not null default 'pt' check (idioma in ('pt', 'en')),
  nivel           text not null check (nivel in ('entidade', 'programa', 'modulo', 'projeto')),
  singular        text not null check (btrim(singular) <> ''),
  plural          text not null check (btrim(plural) <> ''),
  genero          text not null default 'm' check (genero in ('m', 'f')),
  atualizado_em   timestamptz not null default now(),

  -- Uma linha é a predefinição (os dois nulos), de um tipo, ou de uma entidade
  constraint terminologia_um_alvo check (tipo_entidade is null or id_entidade is null),
  constraint terminologia_unica unique nulls not distinct (tipo_entidade, id_entidade, idioma, nivel)
);

comment on table public.terminologia is
  'Nomes dos níveis da hierarquia por tipo de entidade (ou por entidade), com singular, plural e género.';

-- ─── Permissões ───────────────────────────────────────────────────

create or replace function public.e_superadmin()
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (
    select 1 from tipo_utilizador
     where id_utilizador = auth.uid() and role = 'superadmin'
  );
$$;

grant execute on function public.e_superadmin() to anon, authenticated;

alter table public.terminologia enable row level security;

drop policy if exists "terminologia_leitura" on public.terminologia;
create policy "terminologia_leitura" on public.terminologia
  for select to anon, authenticated using (true);

drop policy if exists "terminologia_escrita" on public.terminologia;
create policy "terminologia_escrita" on public.terminologia
  for all to authenticated
  using (public.e_superadmin()) with check (public.e_superadmin());

-- Data da última alteração (para o painel mostrar quando foi mudado)
create or replace function public.terminologia_atualizada()
returns trigger
language plpgsql
as $$
begin
  new.atualizado_em := now();
  return new;
end;
$$;

drop trigger if exists terminologia_atualizada on public.terminologia;
create trigger terminologia_atualizada
  before update on public.terminologia
  for each row execute function public.terminologia_atualizada();


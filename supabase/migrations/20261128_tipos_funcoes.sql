-- ════════════════════════════════════════════════════════════════════
-- Tipos de entidade, presets, funções e permissões
--
-- Cada tipo de entidade (Escola, Hospital, Empresa…) passa a ter o seu
-- vocabulário, as suas funções (cargos) e a configuração do painel.
-- Um preset é um modelo pronto: aplicar um preset cria um tipo novo
-- como cópia independente, que depois se edita à vontade.
--
-- As permissões deixam de depender do role fixo (e_staff, gere_modulo):
-- cada pessoa tem funções num âmbito (entidade, programa ou módulo) e
-- a função tem_permissao(...) decide tudo. Isto corrige o problema de
-- um gestor poder editar qualquer entidade.
--
-- Transição: as páginas antigas (/admin, /gestor, /utilizador) ainda
-- escrevem na tabela tipo_utilizador. Um trigger copia essas linhas
-- para as tabelas novas, por isso continuam a funcionar até o painel
-- novo (/painel) as substituir. Depois disso, tipo_utilizador sai.
--
-- Ordem: 1. catálogo · 2. tabelas · 3. terminologia · 4. permissões ·
--        5. presets · 6. dados antigos · 7. regras (RLS) e triggers
--
-- Pode ser corrida mais do que uma vez. Fazer cópia de segurança antes.
-- ════════════════════════════════════════════════════════════════════


-- ─── 1. Catálogo de permissões ─────────────────────────────────────
-- Fixo no código (src/lib/permissoes.js) e validado aqui.

create or replace function public.catalogo_permissoes()
returns text[]
language sql
immutable
as $$
  select array[
    'submeter_trabalhos',     -- submeter trabalhos para aprovação
    'aprovar_trabalhos',      -- aprovar e rejeitar trabalhos
    'gerir_projetos',         -- criar e editar projetos e os seus ficheiros
    'gerir_conteudo_3d',      -- modelos 3D e vídeos de fundo
    'usar_criador_video',     -- usar o criador de vídeo
    'gerir_modulos',          -- criar e editar módulos
    'gerir_programas',        -- criar e editar programas
    'gerir_entidade',         -- dados e logo da entidade
    'gerir_membros',          -- dar e tirar funções (só de nível inferior)
    'gerir_funcoes_e_termos', -- termos próprios da entidade
    'ver_estatisticas'        -- números do painel
  ]::text[];
$$;

-- Texto livre → slug ("Câmara Municipal" → "camara-municipal")
create or replace function public.slug_de(texto text)
returns text
language sql
immutable
as $$
  select trim(both '-' from regexp_replace(
    lower(translate(btrim(coalesce(texto, '')),
      'áàâãäéèêëíìîïóòôõöúùûüçñÁÀÂÃÄÉÈÊËÍÌÎÏÓÒÔÕÖÚÙÛÜÇÑ',
      'aaaaaeeeeiiiiooooouuuucnaaaaaeeeeiiiiooooouuuucn')),
    '[^a-z0-9]+', '-', 'g'));
$$;


-- ─── 2. Tabelas ─────────────────────────────────────────────────────

-- Tipos de entidade. A config diz que partes do painel estão ligadas:
--   { "biblioteca", "criador_video", "modelos_3d", "aprovacao",
--     "identificador_obrigatorio": bool,
--     "grupo1" / "grupo2": { "ligado": bool, "formato": "ordinal" | "nome_numero" } }
--   ordinal → "1.º ano" · nome_numero → "Piso 1"
create table if not exists public.tipos_entidade (
  id_tipo    bigint generated by default as identity primary key,
  slug       text not null unique check (slug ~ '^[a-z0-9]+(-[a-z0-9]+)*$'),
  nome       text not null check (btrim(nome) <> ''),
  descricao  text,
  config     jsonb not null default '{}'::jsonb check (jsonb_typeof(config) = 'object'),
  criado_em  timestamptz not null default now()
);

comment on table public.tipos_entidade is
  'Tipos de entidade (escola, hospital…): vocabulário, funções e partes do painel.';

-- Presets: modelos prontos. dados = { config, termos: {pt: {chave: termo}}, funcoes: [...] }
create table if not exists public.presets (
  id_preset      bigint generated by default as identity primary key,
  slug           text not null unique check (slug ~ '^[a-z0-9]+(-[a-z0-9]+)*$'),
  nome           text not null check (btrim(nome) <> ''),
  descricao      text,
  dados          jsonb not null check (jsonb_typeof(dados) = 'object'),
  atualizado_em  timestamptz not null default now()
);

comment on table public.presets is
  'Modelos de tipo de entidade. Aplicar um preset cria uma cópia independente.';

-- Funções (cargos) de cada tipo. nivel: quanto maior, mais alto na hierarquia.
-- ambito: onde a função se atribui (entidade inteira, um programa ou um módulo).
create table if not exists public.funcoes (
  id_funcao   bigint generated by default as identity primary key,
  id_tipo     bigint not null references public.tipos_entidade (id_tipo) on delete cascade,
  slug        text not null check (slug ~ '^[a-z0-9]+(_[a-z0-9]+)*$'),
  ambito      text not null check (ambito in ('entidade', 'programa', 'modulo')),
  nivel       integer not null check (nivel between 1 and 100),
  permissoes  text[] not null default '{}' check (permissoes <@ public.catalogo_permissoes()),
  e_base      boolean not null default false,
  criado_em   timestamptz not null default now(),
  constraint funcoes_unica unique (id_tipo, slug)
);

-- Cada tipo tem no máximo uma função base (a de quem entra)
create unique index if not exists funcoes_uma_base on public.funcoes (id_tipo) where e_base;

comment on table public.funcoes is
  'Funções de cada tipo de entidade, com âmbito, nível e permissões. O nome está na terminologia (chave funcao.<slug>).';

-- Quem administra a plataforma (substitui o role superadmin)
create table if not exists public.administradores_plataforma (
  id_utilizador  uuid primary key references public.utilizadores (id_utilizadores) on delete cascade,
  criado_em      timestamptz not null default now()
);

-- Ligação da pessoa à entidade, com o número de identificação
-- (número de aluno, número mecanográfico…). O número é por entidade.
create table if not exists public.membros_entidade (
  id_membro      bigint generated by default as identity primary key,
  id_utilizador  uuid not null references public.utilizadores (id_utilizadores) on delete cascade,
  id_entidade    bigint not null references public.entidade (id_entidade) on delete cascade,
  identificador  text check (identificador is null or (btrim(identificador) <> '' and length(identificador) <= 40)),
  criado_em      timestamptz not null default now(),
  constraint membros_entidade_unico unique (id_utilizador, id_entidade),
  constraint membros_entidade_identificador_unico unique (id_entidade, identificador)
);

comment on column public.membros_entidade.identificador is
  'Número da pessoa nesta entidade. Nunca aparece nas páginas públicas.';

-- Atribuições: uma pessoa tem uma função num âmbito (só um dos três)
create table if not exists public.atribuicoes (
  id_atribuicao  bigint generated by default as identity primary key,
  id_utilizador  uuid not null references public.utilizadores (id_utilizadores) on delete cascade,
  id_funcao      bigint not null references public.funcoes (id_funcao) on delete cascade,
  id_entidade    bigint references public.entidade (id_entidade) on delete cascade,
  id_programa    bigint references public.programa (id_programa) on delete cascade,
  id_modulo      bigint references public.modulo (id_modulo) on delete cascade,
  -- Transição: a linha de tipo_utilizador que deu origem a esta
  id_legado      bigint unique references public.tipo_utilizador (id_tipo_utilizador) on delete cascade,
  criado_em      timestamptz not null default now(),
  constraint atribuicoes_um_ambito check (num_nonnulls(id_entidade, id_programa, id_modulo) = 1),
  constraint atribuicoes_unica unique nulls not distinct (id_utilizador, id_funcao, id_entidade, id_programa, id_modulo)
);

create index if not exists atribuicoes_utilizador_idx on public.atribuicoes (id_utilizador);
create index if not exists atribuicoes_modulo_idx     on public.atribuicoes (id_modulo)   where id_modulo   is not null;
create index if not exists atribuicoes_programa_idx   on public.atribuicoes (id_programa) where id_programa is not null;
create index if not exists atribuicoes_entidade_idx   on public.atribuicoes (id_entidade) where id_entidade is not null;



-- "Guardar este tipo como preset" (substitui um preset com o mesmo slug)
create or replace function public.guardar_tipo_como_preset(
  p_id_tipo bigint, p_slug text, p_nome text, p_descricao text default null)
returns bigint
language plpgsql
security definer
set search_path = public
as $$
declare
  v_slug  text;
  v_dados jsonb;
  v_id    bigint;
begin
  if auth.uid() is not null and not public.e_superadmin() then
    raise exception 'Só um administrador da plataforma guarda presets.' using errcode = '42501';
  end if;

  select slug into v_slug from tipos_entidade where id_tipo = p_id_tipo;
  if v_slug is null then
    raise exception 'O tipo de entidade % não existe.', p_id_tipo;
  end if;

  v_dados := jsonb_build_object(
    'config', (select config from tipos_entidade where id_tipo = p_id_tipo),
    'termos', (
      select coalesce(jsonb_object_agg(idioma, termos), '{}'::jsonb)
        from (select idioma,
                     jsonb_object_agg(chave, jsonb_build_object('singular', singular, 'plural', plural, 'genero', genero)) as termos
                from terminologia
               where tipo_entidade = v_slug and id_entidade is null and chave not like 'funcao.%'
               group by idioma) x),
    'funcoes', (
      select coalesce(jsonb_agg(jsonb_build_object(
               'slug', f.slug, 'ambito', f.ambito, 'nivel', f.nivel,
               'permissoes', to_jsonb(f.permissoes), 'e_base', f.e_base,
               'termos', (select coalesce(jsonb_object_agg(t.idioma, jsonb_build_object(
                                 'singular', t.singular, 'plural', t.plural, 'genero', t.genero)), '{}'::jsonb)
                            from terminologia t
                           where t.tipo_entidade = v_slug and t.id_entidade is null
                             and t.chave = 'funcao.' || f.slug))
             order by f.nivel desc), '[]'::jsonb)
        from funcoes f where f.id_tipo = p_id_tipo));

  insert into presets (slug, nome, descricao, dados)
  values (p_slug, p_nome, p_descricao, v_dados)
  on conflict (slug) do update
     set nome = excluded.nome, descricao = excluded.descricao,
         dados = excluded.dados, atualizado_em = now()
  returning id_preset into v_id;

  return v_id;
end;
$$;

grant execute on function public.guardar_tipo_como_preset(bigint, text, text, text) to authenticated;



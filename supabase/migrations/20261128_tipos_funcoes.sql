create or replace function public.proteger_media()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  v_novo          boolean := tg_op = 'INSERT';
  v_estado_mudou  boolean;
  v_modulo_mudou  boolean;
  v_gere          boolean;
begin
  -- SQL Editor e service_role (auth.uid() nulo) e superadmin não são limitados.
  -- Também não as alterações feitas pela própria base de dados (por exemplo,
  -- apagar um módulo põe id_modulo a nulo nos trabalhos dele).
  if auth.uid() is null or pg_trigger_depth() > 1 or public.e_superadmin() then
    return new;
  end if;

  v_estado_mudou := v_novo or new.status is distinct from old.status;
  v_modulo_mudou := v_novo or new.id_modulo is distinct from old.id_modulo;

  -- Aprovar ou rejeitar (ou mudar de módulo um trabalho já decidido)
  if new.status in ('aprovado', 'rejeitado') and (v_estado_mudou or v_modulo_mudou)
     and not public.tem_permissao('aprovar_trabalhos', new.id_modulo) then
    raise exception 'Só quem aprova trabalhos neste módulo pode aprovar ou rejeitar este conteúdo.'
      using errcode = '42501';
  end if;

  -- Submeter para aprovação
  if new.status = 'pendente' and (v_estado_mudou or v_modulo_mudou)
     and not public.tem_permissao('submeter_trabalhos', new.id_modulo) then
    raise exception 'Não tens permissão para submeter trabalhos neste módulo.' using errcode = '42501';
  end if;

  -- Conteúdo oficial (sem estado, é público), ficheiros de projetos e logos: só quem gere
  v_gere := public.pode_gerir_media(new.id_media_items, new.id_modulo, new.id_programa, new.id_entidade, new.id_projetos)
         or (new.status is null and new.id_modulo is null and new.id_projetos is null
             and new.tipo in ('modelo3d', 'video')
             and public.tem_permissao_dentro('gerir_conteudo_3d', null, new.id_programa, new.id_entidade));

  if not v_gere and (
       (new.status is null and v_estado_mudou)
    or (new.id_projetos is not null and (v_novo or new.id_projetos is distinct from old.id_projetos))
    or (new.tipo = 'logo3d' and (v_novo or new.tipo is distinct from old.tipo)))
  then
    raise exception 'Só quem gere o conteúdo pode publicar este tipo de conteúdo.' using errcode = '42501';
  end if;

  return new;
end;
$$;

revoke execute on function public.proteger_media() from public, anon, authenticated;


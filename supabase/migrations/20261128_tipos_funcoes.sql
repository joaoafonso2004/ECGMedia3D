  for each row execute function public.proteger_media();

-- 7.9 Notificações: o pedido de aprovação vai para quem aprova no módulo
-- (ou, se não houver, no programa, ou na entidade); sem ninguém, para os superadmins
create or replace function public.notificar_estado_media()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  v_titulo   text := coalesce(nullif(trim(new.titulo), ''), 'Sem título');
  v_autor    text;
  v_modulo   text;
  v_avisados integer;
begin
  if tg_op = 'UPDATE' and new.status is not distinct from old.status then
    return new;
  end if;

  select nome into v_autor  from utilizadores where id_utilizadores = new.id_autor;
  select nome into v_modulo from modulo       where id_modulo       = new.id_modulo;

  if new.status = 'pendente' then
    insert into notificacoes (id_destinatario, tipo, titulo, mensagem, link, id_media_items)
    select q, 'submissao_pendente', 'Novo pedido de aprovação',
           coalesce(v_autor, 'Um aluno') || ' submeteu "' || v_titulo || '"'
             || coalesce(' em ' || v_modulo, '') || '.',
           '/gestor/aprovacoes', new.id_media_items
      from public.quem_aprova(new.id_modulo) q
     where q is distinct from new.id_autor;

    get diagnostics v_avisados = row_count;

    if v_avisados = 0 then
      insert into notificacoes (id_destinatario, tipo, titulo, mensagem, link, id_media_items)
      select a.id_utilizador, 'submissao_pendente', 'Pedido de aprovação sem gestor',
             coalesce(v_autor, 'Um aluno') || ' submeteu "' || v_titulo || '"'
               || coalesce(' em ' || v_modulo, '')
               || ', mas ainda ninguém aprova trabalhos neste módulo.',
             '/gestor/aprovacoes', new.id_media_items
        from administradores_plataforma a;
    end if;

    return new;
  end if;

  if tg_op <> 'UPDATE' then
    return new;
  end if;

  if old.status = 'pendente' then
    update notificacoes
       set lida = true
     where id_media_items = new.id_media_items
       and tipo = 'submissao_pendente'
       and lida = false;
  end if;

  -- Sem autor, ou foi o próprio autor que mudou o estado: não há a quem avisar
  if new.id_autor is null or new.id_autor = auth.uid() then
    return new;
  end if;

  if old.status = 'pendente' and new.status = 'aprovado' then
    insert into notificacoes (id_destinatario, tipo, titulo, mensagem, link, id_media_items)
    values (new.id_autor, 'conteudo_aprovado', 'Conteúdo aprovado',
            '"' || v_titulo || '" foi aprovado' || coalesce(' em ' || v_modulo, '')
              || ' e já está visível na galeria.',
            '/utilizador/biblioteca', new.id_media_items);

  elsif old.status = 'pendente' and new.status = 'rejeitado' then
    insert into notificacoes (id_destinatario, tipo, titulo, mensagem, link, id_media_items)
    values (new.id_autor, 'conteudo_rejeitado', 'Conteúdo não aprovado',
            '"' || v_titulo || '" não foi aprovado' || coalesce(' em ' || v_modulo, '')
              || '. Podes rever o trabalho e voltar a submeter.',
            '/utilizador/biblioteca', new.id_media_items);

  elsif old.status = 'aprovado' and new.status = 'pessoal' then
    insert into notificacoes (id_destinatario, tipo, titulo, mensagem, link, id_media_items)
    values (new.id_autor, 'conteudo_removido', 'Conteúdo removido da galeria',
            '"' || v_titulo || '" foi removido da galeria'
              || coalesce(' de ' || v_modulo, '') || ' e voltou à tua biblioteca.',
            '/utilizador/biblioteca', new.id_media_items);
  end if;

  return new;
end;
$$;

revoke execute on function public.notificar_estado_media() from public, anon, authenticated;

-- 7.10 Espelho da tabela antiga: o que as páginas antigas escrevem em
-- tipo_utilizador passa logo para as tabelas novas
create or replace function public.espelhar_tipo_utilizador()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  if tg_op in ('UPDATE', 'DELETE') then
    delete from atribuicoes where id_legado = old.id_tipo_utilizador;
    if old.role = 'superadmin' and not exists (
         select 1 from tipo_utilizador
          where id_utilizador = old.id_utilizador and role = 'superadmin'
            and id_tipo_utilizador <> old.id_tipo_utilizador) then
      delete from administradores_plataforma where id_utilizador = old.id_utilizador;
    end if;
    if tg_op = 'DELETE' then
      return old;
    end if;
  end if;

  perform public.espelhar_cargo(new.id_tipo_utilizador, new.id_utilizador, new.role, new.id_entidade, new.id_modulo);
  return new;
end;
$$;

revoke execute on function public.espelhar_tipo_utilizador() from public, anon, authenticated;

drop trigger if exists tipo_utilizador_espelho on public.tipo_utilizador;
create trigger tipo_utilizador_espelho
  after insert or update or delete on public.tipo_utilizador
  for each row execute function public.espelhar_tipo_utilizador();


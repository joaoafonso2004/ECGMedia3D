insert into public.tipos_entidade (slug, nome)
select v.slug, coalesce(p.nome, initcap(replace(v.slug, '-', ' ')))
  from (select tipo as slug from public.entidade where tipo is not null
        union
        select tipo_entidade from public.terminologia where tipo_entidade is not null) v
  left join public.presets p on p.slug = v.slug
on conflict (slug) do nothing;

-- Os tipos sem funções recebem o preset com o mesmo nome (ou o "vazio")
do $$
declare t record;
begin
  for t in
    select te.id_tipo, coalesce(p.slug, 'vazio') as preset
      from public.tipos_entidade te
      left join public.presets p on p.slug = te.slug
     where not exists (select 1 from public.funcoes f where f.id_tipo = te.id_tipo)
  loop
    perform public.completar_tipo(t.id_tipo, t.preset);
  end loop;
end $$;


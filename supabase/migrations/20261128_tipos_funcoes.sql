-- Mudar o tipo da entidade, ou mudar um programa/módulo de sítio, também
-- pede permissão no destino (a regra só consegue ver a linha antiga)
create or replace function public.proteger_estrutura()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  if tg_table_name = 'entidade' then
    -- Mudar o slug de um tipo também muda entidade.tipo (on update cascade):
    -- isso não é mudar de tipo, por isso só conta se o tipo antigo ainda existir
    if new.tipo is distinct from old.tipo
       and (old.tipo is null or exists (select 1 from tipos_entidade where slug = old.tipo)) then
      if auth.uid() is not null and not public.e_superadmin() then
        raise exception 'Só um administrador da plataforma muda o tipo de uma entidade.' using errcode = '42501';
      end if;
      if exists (select 1 from atribuicoes a
                   cross join lateral cadeia_ambito(a.id_modulo, a.id_programa, a.id_entidade) c
                  where c.id_entidade = new.id_entidade) then
        raise exception 'Esta entidade tem funções atribuídas: tira-as antes de mudar o tipo.' using errcode = '23514';
      end if;
    end if;
    return new;
  end if;

  if auth.uid() is null or public.e_superadmin() then
    return new;
  end if;

  if tg_table_name = 'programa' then
    if new.id_entidade is distinct from old.id_entidade
       and not public.tem_permissao('gerir_programas', null, null, new.id_entidade) then
      raise exception 'Sem permissão para mudar este programa de entidade.' using errcode = '42501';
    end if;
  elsif tg_table_name = 'modulo' then
    if new.id_programa is distinct from old.id_programa
       and not public.tem_permissao('gerir_modulos', null, new.id_programa) then
      raise exception 'Sem permissão para mudar este módulo de programa.' using errcode = '42501';
    end if;
  end if;
  return new;
end;
$$;


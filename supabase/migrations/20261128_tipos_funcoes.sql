-- 6.2 Cargos antigos → tabelas novas. A mesma função serve para a
-- migração e para o espelho das páginas antigas (secção 7).
--   superadmin             → administradores_plataforma
--   gestor_disciplina + M  → a função de módulo mais alta do tipo (Professor na Escola), em M
--   utilizador + M         → a função base (Aluno na Escola), em M
--   gestor / utilizador    → só a ligação à entidade (o 'gestor' sozinho não dá permissões)
create or replace function public.espelhar_cargo(
  p_legado bigint, p_utilizador uuid, p_role text, p_entidade bigint, p_modulo bigint)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  v_tipo   bigint;
  v_funcao bigint;
  v_ent    bigint;
begin
  if p_role = 'superadmin' then
    insert into administradores_plataforma (id_utilizador) values (p_utilizador) on conflict do nothing;
    return;
  end if;

  if p_modulo is not null and p_role in ('gestor_disciplina', 'utilizador') then
    select te.id_tipo into v_tipo
      from modulo m
      join programa p on p.id_programa = m.id_programa
      join entidade e on e.id_entidade = p.id_entidade
      join tipos_entidade te on te.slug = e.tipo
     where m.id_modulo = p_modulo;

    if p_role = 'gestor_disciplina' then
      select id_funcao into v_funcao from funcoes
       where id_tipo = v_tipo and ambito = 'modulo' and not e_base
       order by nivel desc limit 1;
    else
      select id_funcao into v_funcao from funcoes
       where id_tipo = v_tipo and ambito = 'modulo' and e_base;
    end if;

    if v_funcao is null then
      raise notice 'Sem função para o cargo % no módulo % (a entidade não tem tipo?).', p_role, p_modulo;
      return;
    end if;

    insert into atribuicoes (id_utilizador, id_funcao, id_modulo, id_legado)
    values (p_utilizador, v_funcao, p_modulo, p_legado)
    on conflict do nothing;
    return;
  end if;

  v_ent := coalesce(p_entidade, (select id_entidade from utilizadores where id_utilizadores = p_utilizador));
  if v_ent is not null then
    insert into membros_entidade (id_utilizador, id_entidade) values (p_utilizador, v_ent) on conflict do nothing;
  end if;
end;
$$;


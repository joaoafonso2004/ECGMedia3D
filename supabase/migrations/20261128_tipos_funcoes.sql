update public.entidade
   set tipo = nullif(public.slug_de(tipo), '')
 where tipo is distinct from nullif(public.slug_de(tipo), '');

update public.terminologia
   set tipo_entidade = public.slug_de(tipo_entidade)
 where tipo_entidade is not null and tipo_entidade <> public.slug_de(tipo_entidade);


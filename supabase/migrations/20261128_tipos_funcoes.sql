-- ─── 4. Permissões ──────────────────────────────────────────────────

create or replace function public.e_superadmin()
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (select 1 from administradores_plataforma where id_utilizador = auth.uid());
$$;

grant execute on function public.e_superadmin() to anon, authenticated;

-- Módulo → programa → entidade. Se vier um módulo, o programa e a
-- entidade saem dele (e não do que o pedido diz), para não se poder
-- enganar a verificação com ids trocados.
create or replace function public.cadeia_ambito(p_modulo bigint, p_programa bigint, p_entidade bigint)
returns table (id_modulo bigint, id_programa bigint, id_entidade bigint)
language sql
stable
security definer
set search_path = public
as $$
  with m as (
    select mo.id_modulo, mo.id_programa from modulo mo where mo.id_modulo = p_modulo
  ), p as (
    select pr.id_programa, pr.id_entidade from programa pr
     where pr.id_programa = case when p_modulo is not null then (select m.id_programa from m) else p_programa end
  )
  select (select m.id_modulo from m),
         (select p.id_programa from p),
         case when p_modulo is not null or p_programa is not null
              then (select p.id_entidade from p)
              else (select e.id_entidade from entidade e where e.id_entidade = p_entidade)
         end;
$$;

revoke execute on function public.cadeia_ambito(bigint, bigint, bigint) from public, anon, authenticated;

-- A pessoa com sessão iniciada tem esta permissão neste alvo?
-- Verdadeiro se for administrador da plataforma, ou se tiver uma
-- atribuição cujo âmbito contém o alvo e cuja função tem a permissão.
-- O alvo é o mais específico que vier (módulo, senão programa, senão entidade).
create or replace function public.tem_permissao(
  p_perm text, p_modulo bigint default null, p_programa bigint default null, p_entidade bigint default null)
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select public.e_superadmin() or exists (
    select 1
      from public.cadeia_ambito(p_modulo, p_programa, p_entidade) t
      join atribuicoes a
        on a.id_utilizador = auth.uid()
       and (a.id_entidade = t.id_entidade or a.id_programa = t.id_programa or a.id_modulo = t.id_modulo)
      join funcoes f
        on f.id_funcao = a.id_funcao and p_perm = any (f.permissoes)
  );
$$;

grant execute on function public.tem_permissao(text, bigint, bigint, bigint) to anon, authenticated;

-- Como tem_permissao, mas também vale uma atribuição DENTRO do alvo
-- (por exemplo, um professor de um módulo do programa). Serve para listas
-- e para o fluxo antigo do gestor, que cria o modelo antes de o ligar ao módulo.
create or replace function public.tem_permissao_dentro(
  p_perm text, p_modulo bigint default null, p_programa bigint default null, p_entidade bigint default null)
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select public.tem_permissao(p_perm, p_modulo, p_programa, p_entidade) or exists (
    select 1
      from public.cadeia_ambito(p_modulo, p_programa, p_entidade) t
      join atribuicoes a on a.id_utilizador = auth.uid()
      join funcoes f on f.id_funcao = a.id_funcao and p_perm = any (f.permissoes)
      cross join lateral public.cadeia_ambito(a.id_modulo, a.id_programa, a.id_entidade) s
     where (t.id_modulo is null and t.id_programa is not null and s.id_programa = t.id_programa)
        or (t.id_modulo is null and t.id_programa is null and s.id_entidade = t.id_entidade)
  );
$$;

grant execute on function public.tem_permissao_dentro(text, bigint, bigint, bigint) to anon, authenticated;

-- Proteção contra subir de cargo: só se dá uma função de nível inferior
-- ao da nossa, dentro do nosso âmbito, e se a nossa tiver gerir_membros.
create or replace function public.pode_atribuir(
  p_funcao bigint, p_entidade bigint, p_programa bigint, p_modulo bigint)
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select public.e_superadmin() or exists (
    select 1
      from public.cadeia_ambito(p_modulo, p_programa, p_entidade) t
      join atribuicoes a
        on a.id_utilizador = auth.uid()
       and (a.id_entidade = t.id_entidade or a.id_programa = t.id_programa or a.id_modulo = t.id_modulo)
      join funcoes f
        on f.id_funcao = a.id_funcao and 'gerir_membros' = any (f.permissoes)
      join funcoes alvo
        on alvo.id_funcao = p_funcao and alvo.nivel < f.nivel
  );
$$;

grant execute on function public.pode_atribuir(bigint, bigint, bigint, bigint) to authenticated;

-- Quem pode gerir este conteúdo (modelos, vídeos, ficheiros de projetos, logos)?
-- Conta o alvo do próprio conteúdo, os módulos a que está ligado
-- (modulo_media) e o módulo do projeto a que pertence.
create or replace function public.pode_gerir_media(
  p_media bigint, p_modulo bigint, p_programa bigint, p_entidade bigint, p_projeto bigint)
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select public.e_superadmin()
      or (coalesce(p_modulo, p_programa, p_entidade) is not null
          and public.tem_permissao('gerir_conteudo_3d', p_modulo, p_programa, p_entidade))
      or exists (select 1 from modulo_media mm
                  where mm.id_media_items = p_media
                    and public.tem_permissao('gerir_conteudo_3d', mm.id_modulo))
      or exists (select 1 from projetos pj
                  where pj.id_projetos = p_projeto
                    and public.tem_permissao('gerir_projetos', pj.id_modulo));
$$;

grant execute on function public.pode_gerir_media(bigint, bigint, bigint, bigint, bigint) to anon, authenticated;

-- Quem aprova os trabalhos deste módulo: primeiro quem está no módulo,
-- senão no programa, senão na entidade (é a quem vão as notificações)
create or replace function public.quem_aprova(p_modulo bigint)
returns setof uuid
language sql
stable
security definer
set search_path = public
as $$
  with c as (
    select a.id_utilizador,
           case when a.id_modulo is not null then 0 when a.id_programa is not null then 1 else 2 end as distancia
      from public.cadeia_ambito(p_modulo, null, null) t
      join atribuicoes a
        on a.id_entidade = t.id_entidade or a.id_programa = t.id_programa or a.id_modulo = t.id_modulo
      join funcoes f
        on f.id_funcao = a.id_funcao and 'aprovar_trabalhos' = any (f.permissoes)
  )
  select distinct id_utilizador from c where distancia = (select min(distancia) from c);
$$;

revoke execute on function public.quem_aprova(bigint) from public, anon, authenticated;

-- Compatibilidade: as funções antigas passam a usar as tabelas novas
create or replace function public.gere_modulo(p_modulo bigint)
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select public.tem_permissao('gerir_membros', p_modulo);
$$;

create or replace function public.e_staff()
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select public.e_superadmin() or exists (
    select 1 from atribuicoes a join funcoes f on f.id_funcao = a.id_funcao
     where a.id_utilizador = auth.uid()
       and f.permissoes && array['aprovar_trabalhos', 'gerir_projetos', 'gerir_conteudo_3d', 'gerir_modulos',
                                 'gerir_programas', 'gerir_entidade', 'gerir_membros', 'gerir_funcoes_e_termos']
  );
$$;



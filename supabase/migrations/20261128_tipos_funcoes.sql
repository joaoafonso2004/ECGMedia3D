do $$
declare c record;
begin
  for c in select * from public.tipo_utilizador order by id_tipo_utilizador loop
    perform public.espelhar_cargo(c.id_tipo_utilizador, c.id_utilizador, c.role, c.id_entidade, c.id_modulo);
  end loop;
end $$;


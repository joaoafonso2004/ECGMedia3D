-- 7.1 Atribuições: âmbito certo, função do tipo da entidade, e liga a pessoa à entidade
create or replace function public.validar_atribuicao()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  v_funcao  funcoes%rowtype;
  v_ambito  text := case when new.id_modulo is not null then 'modulo'
                         when new.id_programa is not null then 'programa'
                         else 'entidade' end;
  v_ent     bigint;
  v_tipo    bigint;
begin
  select * into v_funcao from funcoes where id_funcao = new.id_funcao;
  if not found then
    raise exception 'A função % não existe.', new.id_funcao using errcode = '23503';
  end if;

  if v_funcao.ambito <> v_ambito then
    raise exception 'A função "%" atribui-se %, e não %.', v_funcao.slug,
      case v_funcao.ambito when 'entidade' then 'à entidade inteira' when 'programa' then 'a um programa' else 'a um módulo' end,
      case v_ambito        when 'entidade' then 'à entidade inteira' when 'programa' then 'a um programa' else 'a um módulo' end
      using errcode = '23514';
  end if;

  select c.id_entidade into v_ent from cadeia_ambito(new.id_modulo, new.id_programa, new.id_entidade) c;
  select te.id_tipo into v_tipo
    from entidade e join tipos_entidade te on te.slug = e.tipo
   where e.id_entidade = v_ent;

  if v_tipo is distinct from v_funcao.id_tipo then
    raise exception 'Esta função não pertence ao tipo desta entidade.' using errcode = '23514';
  end if;

  insert into membros_entidade (id_utilizador, id_entidade)
  values (new.id_utilizador, v_ent)
  on conflict do nothing;

  return new;
end;
$$;

revoke execute on function public.validar_atribuicao() from public, anon, authenticated;


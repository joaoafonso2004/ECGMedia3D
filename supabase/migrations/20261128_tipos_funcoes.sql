-- Copia um preset para um tipo: a configuração, os termos e as funções
-- que o tipo ainda não tem (o que já existe fica como está)
create or replace function public.completar_tipo(p_id_tipo bigint, p_preset text)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  v_dados jsonb;
  v_slug  text;
  f       jsonb;
begin
  select dados into v_dados from presets where slug = p_preset;
  if v_dados is null then
    raise exception 'O preset "%" não existe.', p_preset;
  end if;

  update tipos_entidade
     set config = coalesce(v_dados -> 'config', '{}'::jsonb) || config
   where id_tipo = p_id_tipo
  returning slug into v_slug;

  if v_slug is null then
    raise exception 'O tipo de entidade % não existe.', p_id_tipo;
  end if;

  insert into terminologia (tipo_entidade, idioma, chave, singular, plural, genero)
  select v_slug, l.key, t.key, t.value ->> 'singular', t.value ->> 'plural', coalesce(t.value ->> 'genero', 'm')
    from jsonb_each(coalesce(v_dados -> 'termos', '{}'::jsonb)) l,
         jsonb_each(l.value) t
  on conflict on constraint terminologia_unica do nothing;

  for f in select * from jsonb_array_elements(coalesce(v_dados -> 'funcoes', '[]'::jsonb)) loop
    insert into funcoes (id_tipo, slug, ambito, nivel, permissoes, e_base)
    values (p_id_tipo, f ->> 'slug', f ->> 'ambito', (f ->> 'nivel')::integer,
            array(select jsonb_array_elements_text(coalesce(f -> 'permissoes', '[]'::jsonb))),
            coalesce((f ->> 'e_base')::boolean, false)
              and not exists (select 1 from funcoes b where b.id_tipo = p_id_tipo and b.e_base))
    on conflict on constraint funcoes_unica do nothing;

    insert into terminologia (tipo_entidade, idioma, chave, singular, plural, genero)
    select v_slug, l.key, 'funcao.' || (f ->> 'slug'),
           l.value ->> 'singular', l.value ->> 'plural', coalesce(l.value ->> 'genero', 'm')
      from jsonb_each(coalesce(f -> 'termos', '{}'::jsonb)) l
    on conflict on constraint terminologia_unica do nothing;
  end loop;
end;
$$;

revoke execute on function public.completar_tipo(bigint, text) from public, anon, authenticated;

-- "Novo tipo": cria um tipo a partir de um preset (ou do "vazio"), como cópia independente
create or replace function public.aplicar_preset(
  p_preset text, p_slug text, p_nome text, p_descricao text default null)
returns bigint
language plpgsql
security definer
set search_path = public
as $$
declare
  v_id bigint;
begin
  if auth.uid() is not null and not public.e_superadmin() then
    raise exception 'Só um administrador da plataforma cria tipos de entidade.' using errcode = '42501';
  end if;

  insert into tipos_entidade (slug, nome, descricao)
  values (p_slug, p_nome, p_descricao)
  returning id_tipo into v_id;

  perform public.completar_tipo(v_id, p_preset);
  return v_id;
end;
$$;

